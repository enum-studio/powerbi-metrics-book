// Writes src/api/schema.d.ts from apps/api/openapi.json. A binary body (the
// brand logo upload) is typed as a Blob, so a File passes to the typed client
// as it is sent.
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const BLOB = ts.factory.createTypeReferenceNode("Blob");
const nodes = await openapiTS(
  new URL("../../api/openapi.json", import.meta.url),
  {
    transform: (schema) => (schema.format === "binary" ? BLOB : undefined),
  },
);
await writeFile(
  new URL("../src/api/schema.d.ts", import.meta.url),
  `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n${astToString(nodes)}`,
);
